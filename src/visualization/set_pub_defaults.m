function set_pub_defaults()
% SET_PUB_DEFAULTS  Journal-quality default graphics settings (Elsevier-style).
% Call once at the start of any figure-producing routine. Sets serif fonts,
% thin axes, sober line widths and a consistent colour order so every figure
% in the paper looks uniform.
set(groot, ...
    'defaultFigureColor',        'w', ...
    'defaultAxesFontName',       'Times New Roman', ...
    'defaultTextFontName',       'Times New Roman', ...
    'defaultLegendFontName',     'Times New Roman', ...
    'defaultColorbarFontName',   'Times New Roman', ...
    'defaultAxesFontSize',        9, ...
    'defaultAxesLabelFontSizeMultiplier', 1.05, ...
    'defaultAxesTitleFontSizeMultiplier', 1.0, ...
    'defaultLineLineWidth',       1.3, ...
    'defaultAxesLineWidth',       0.75, ...
    'defaultAxesBox',             'on', ...
    'defaultAxesTickDir',         'in', ...
    'defaultAxesTickLength',     [0.018 0.018], ...
    'defaultAxesXMinorTick',      'on', ...
    'defaultAxesYMinorTick',      'on', ...
    'defaultAxesGridAlpha',       0.12, ...
    'defaultLegendBox',           'off', ...
    'defaultFigureInvertHardcopy','off');

% A colour-blind-friendly order (blue, orange, green, red, purple, ...).
co = [0.000 0.447 0.741;
      0.850 0.325 0.098;
      0.466 0.674 0.188;
      0.635 0.078 0.184;
      0.494 0.184 0.556;
      0.301 0.745 0.933;
      0.929 0.694 0.125];
set(groot, 'defaultAxesColorOrder', co);
end
